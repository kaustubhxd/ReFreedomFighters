#!/usr/bin/env node
// Build the native-method catalogue from compiled scripts (names, classes, arg/ret counts, hint).
// usage: node script-vm/catalog.mjs <scripts_dir> [<scripts_dir> ...] > script-vm/natives-catalog.mjs
//        node script-vm/catalog.mjs --json <dirs...>
// Class of a CALL_METHOD target: the o80/o84 object table or exported-variable type of the
// data variable, or the declared type of a state-local variable.
import { loadLibrary } from './fsload.mjs';
import { disassembleFile } from './opcodes.mjs';

export function buildCatalog(libs) {
  const map = new Map();
  const seenFiles = new Set();
  for (const lib of libs) {
    for (const f of lib.byPath.values()) {
      const sig = `${f.name}:${f.code.length}`;
      if (seenFiles.has(sig)) continue;
      seenFiles.add(sig);
      const prog = lib.program(f.relPath);
      const ownStates = prog.states.filter(s => s.file === f.name).sort((a, b) => a.addr - b.addr);
      const { ins } = disassembleFile(prog, f);
      for (const x of ins) {
        if (x.op !== 0x95 && x.op !== 0x96) continue;
        const [a0, mid, hint, flags] = x.args;
        const method = prog.string(mid);
        let cls;
        if (x.op === 0x95) cls = prog.string(a0);
        else if (a0 < 0x8000) {
          const h = prog.hostObjects.find(o => o.offset === a0) ?? prog.valueObjects.find(o => o.offset === a0);
          const v = prog.vars.find(o => o.offset === a0);
          cls = h ? h.type : v ? (v.listType ?? v.type) : `d[0x${a0.toString(16)}]`;
        } else if (!(a0 & 0x4000)) {
          const idx = 0x3fff - (a0 & 0x3fff);
          let st = null;
          for (const s of ownStates) if (s.addr <= x.ip) st = s;
          const chain = []; for (let c = st; c; c = c.parentState) chain.unshift(c);
          const types = chain.flatMap(c => c.varTypeNames);
          cls = types[idx] ?? '?';
        } else cls = '?';
        const kind = x.op === 0x95 ? ((flags >>> 16) & 2 ? 'static' : 'native') : 'method';
        const key = `${cls}.${method}`;
        const e = map.get(key) ?? { cls, method, kind, args: (flags >>> 8) & 0xff, rets: flags & 0xff, hint, count: 0, scripts: new Set() };
        e.count++; e.scripts.add(f.name);
        map.set(key, e);
      }
    }
  }
  return [...map.values()].sort((a, b) => b.count - a.count || a.cls.localeCompare(b.cls) || a.method.localeCompare(b.method))
    .map(e => ({ ...e, scripts: [...e.scripts].sort() }));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const argv = process.argv.slice(2);
  const json = argv[0] === '--json';
  const dirs = json ? argv.slice(1) : argv;
  if (!dirs.length) { console.error('usage: catalog.mjs [--json] <scripts_dir...>'); process.exit(2); }
  const cat = buildCatalog(dirs.map(d => loadLibrary(d)));
  if (json) { console.log(JSON.stringify(cat, null, 1)); process.exit(0); }
  const lines = cat.map(e => `  { cls: ${JSON.stringify(e.cls)}, method: ${JSON.stringify(e.method)}, kind: '${e.kind}', args: ${e.args}, rets: ${e.rets}, hint: 0x${e.hint.toString(16)}, count: ${e.count} },`);
  console.log(`// Generated by script-vm/catalog.mjs from the C01A + C05A scripts (names and signatures only).
// Native methods called by the scripts: class (object table / variable type), method, arg and
// return slot counts (CALL flags), the 'hint' operand (likely the method slot) and use count.
// Regenerate: node script-vm/catalog.mjs <C01A scripts> <C05A scripts> > script-vm/natives-catalog.mjs
export const NATIVE_CATALOG = [
${lines.join('\n')}
];`);
}
