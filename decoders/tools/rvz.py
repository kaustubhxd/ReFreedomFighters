"""Minimal read-only Dolphin RVZ (GameCube) reader. Stdlib only, needs Python 3.14+ (compression.zstd).
Written because the macOS Dolphin.app cask ships no dolphin-tool. Format: Dolphin docs/WiaAndRvz.md.
Usage: python3.14 -I rvz.py header  disc.rvz            -> RVZ + GC disc header info
       python3.14 -I rvz.py list    disc.rvz            -> every FST file: offset size path
       python3.14 -I rvz.py extract disc.rvz outdir [pat...]
           -> writes sys/{boot.bin,bi2.bin,apploader.img,main.dol,fst.bin} and files/<path> for
              FST paths matching any regex pat (no pat = sys only). Existing files are skipped.
RVZ "junk" regions (padding generated by a Lagged Fibonacci seed) are returned as zeros, so a full
ISO rebuilt with this would not be byte-exact; files inside the FST are never junk, so they are exact.
"""
import struct,sys,os,re
from compression import zstd

class RVZ:
    def __init__(s,path):
        s.f=open(path,'rb'); f=s.f
        h=f.read(0x48)
        s.magic,s.version,s.vcompat,dsz=struct.unpack('>4sIII',h[:16])
        if s.magic!=b'RVZ\x01': raise SystemExit('not an RVZ file: %r'%s.magic)
        s.iso_size,s.rvz_size=struct.unpack('>QQ',h[0x24:0x34])
        d=f.read(dsz)
        s.disc_type,s.compression,s.level,s.chunk=struct.unpack('>IIiI',d[:16])
        s.dhead=d[16:0x90]
        o=0x90
        s.n_part,s.part_size,s.part_off=struct.unpack_from('>IIQ',d,o); o+=16+20
        s.n_raw,s.raw_off,s.raw_size,s.n_groups,s.group_off,s.group_size=struct.unpack_from('>IQIIQI',d,o)
        if s.disc_type!=1: raise SystemExit('only GameCube (disc_type 1) supported, got %d'%s.disc_type)
        if s.compression!=5: raise SystemExit('only zstd compression supported, got %d'%s.compression)
        raw=s._table(s.raw_off,s.raw_size)
        s.raws=[struct.unpack_from('>QQII',raw,i*24) for i in range(s.n_raw)]
        g=s._table(s.group_off,s.group_size)
        s.groups=[struct.unpack_from('>III',g,i*12) for i in range(s.n_groups)]
        s.cache=(None,None)
    def _table(s,off,size):
        s.f.seek(off); return zstd.decompress(s.f.read(size))
    def _group(s,gi,length):
        if s.cache[0]==gi: return s.cache[1]
        off4,size,packed=s.groups[gi]; size_=size&0x7fffffff
        if size_==0: data=bytes(length)
        else:
            s.f.seek(off4<<2); data=s.f.read(size_)
            if size&0x80000000: data=zstd.decompress(data)
            if packed:
                out=bytearray(); p=0
                while p<len(data) and len(out)<length:
                    n,=struct.unpack_from('>I',data,p); p+=4
                    if n&0x80000000: out+=bytes(n&0x7fffffff); p+=68   # junk -> zeros, skip 68-byte seed
                    else: out+=data[p:p+n]; p+=n
                data=bytes(out)
        data=data[:length].ljust(length,b'\0')
        s.cache=(gi,data); return data
    def read(s,off,n):
        out=bytearray()
        while n>0:
            if off<0x80:
                k=min(n,0x80-off); out+=s.dhead[off:off+k]; off+=k; n-=k; continue
            for doff,dsize,gidx,ng in s.raws:
                skip=doff%0x8000; start=doff-skip; end=doff+dsize
                if start<=off<end: break
            else: raise ValueError('offset %#x not in any raw data entry'%off)
            rel=off-start; gi=rel//s.chunk; goff=gi*s.chunk
            glen=min(s.chunk,end-start-goff)
            g=s._group(gidx+gi,glen)
            k=min(n,glen-(rel-goff)); out+=g[rel-goff:rel-goff+k]; off+=k; n-=k
        return bytes(out)
    def u32(s,off): return struct.unpack('>I',s.read(off,4))[0]
    def fst(s):
        fo,fs=s.u32(0x424),s.u32(0x428); b=s.read(fo,fs)
        n=struct.unpack_from('>I',b,8)[0]; strs=n*12; out=[]
        def name(i):
            no=struct.unpack_from('>I',b,i*12)[0]&0xffffff; e=b.index(b'\0',strs+no)
            return b[strs+no:e].decode('shift_jis','replace')
        def walk(i,end,prefix):
            while i<end:
                fl,a,c=struct.unpack_from('>III',b,i*12); p=prefix+'/'+name(i)
                if fl>>24: walk(i+1,c,p); i=c
                else: out.append((p,a,c)); i+=1
        walk(1,n,''); return out,fo,fs
    def sysfiles(s):
        dol=s.u32(0x420); fo,fs=s.u32(0x424),s.u32(0x428)
        ah=s.read(0x2440,0x20); asz,atr=struct.unpack('>II',ah[0x14:0x1c])
        dh=s.read(dol,0x100); offs=struct.unpack('>18I',dh[:72]); sizes=struct.unpack('>18I',dh[0x90:0xd8])
        dsz=max([0x100]+[o+z for o,z in zip(offs,sizes) if z])
        return [('boot.bin',0,0x440),('bi2.bin',0x440,0x2000),('apploader.img',0x2440,0x20+asz+atr),
                ('main.dol',dol,dsz),('fst.bin',fo,fs)]

def save(r,path,off,size):
    if os.path.exists(path): print('skip (exists)',path); return
    os.makedirs(os.path.dirname(path),exist_ok=True)
    with open(path,'wb') as w:
        p=0
        while p<size:
            k=min(1<<22,size-p); w.write(r.read(off+p,k)); p+=k
    print('wrote',path,size)

if __name__=='__main__':
    cmd,img=sys.argv[1],sys.argv[2]; r=RVZ(img)
    if cmd=='header':
        h=r.read(0,0x440)
        print('RVZ version %#x (compat %#x), iso_size %d, rvz_size %d, zstd level %d, chunk %#x, raw entries %d, groups %d'%(
            r.version,r.vcompat,r.iso_size,r.rvz_size,r.level,r.chunk,r.n_raw,r.n_groups))
        print('game id',h[:6].decode('ascii','replace'),'disc',h[6],'version',h[7],'audio streaming',h[8],'stream buf',h[9])
        print('magic %#x'%struct.unpack('>I',h[0x1c:0x20]),'title',h[0x20:0x400].split(b'\0')[0].decode('shift_jis','replace'))
        print('dol %#x  fst %#x size %#x max %#x'%struct.unpack('>4I',h[0x420:0x430]))
        print('apploader date',r.read(0x2440,16).split(b'\0')[0].decode('ascii','replace'))
        print('region (bi2) %d'%struct.unpack('>I',r.read(0x440+0x18,4)))
    elif cmd=='list':
        files,_,_=r.fst()
        for p,o,z in files: print('%#010x %10d %s'%(o,z,p))
    elif cmd=='extract':
        out=sys.argv[3]; pats=[re.compile(p,re.I) for p in sys.argv[4:]]
        for n,o,z in r.sysfiles(): save(r,os.path.join(out,'sys',n),o,z)
        if pats:
            for p,o,z in r.fst()[0]:
                if any(x.search(p) for x in pats): save(r,os.path.join(out,'files',p.lstrip('/')),o,z)
